class CopaymentRule(Base):
    """Co-payment rules per scheme, optionally per plan.
    plan_option_id=NULL means the rule applies to ALL plans in the scheme.
    Plan-specific rule takes precedence over scheme-wide NULL rule."""
    __tablename__ = "copayment_rules"

    id = Column(Integer, primary_key=True, index=True)
    scheme_id = Column(Integer, ForeignKey("schemes.id"), nullable=False, index=True)
    plan_option_id = Column(Integer, ForeignKey("plan_options.id"), nullable=True, index=True)
    trigger = Column(String(100), nullable=False)
    # Trigger examples: NON_NETWORK_HOSPITAL, NON_DSP_ONCOLOGY, NO_PREAUTH_PENALTY,
    # NON_DSP_HIV_MEDICATION, NON_DSP_CHRONIC_RENAL_DIALYSIS, OUT_OF_FORMULARY_CHRONIC,
    # VOLUNTARY_CAESAR, HYSTERECTOMY, WISDOM_TEETH_DAY_CLINIC, etc.
    copayment_type = Column(String(20), nullable=False)  # PERCENTAGE | RAND_AMOUNT
    copayment_value = Column(Integer, nullable=False)  # pct * 100 OR rand cents
    description = Column(String(500), nullable=True)
    is_upfront = Column(Boolean, default=True)  # TRUE = paid before treatment; FALSE = penalty after
    is_active = Column(Boolean, default=True)

    plan_option = relationship("PlanOption", back_populates="copayment_rules")

    __table_args__ = (
        UniqueConstraint("scheme_id", "plan_option_id", "trigger",
                         name="uq_copayment_rule"),
    )


class ProviderNetwork(Base):
    """Maps providers to network types per scheme.
    Used by the network validator during adjudication."""
    __tablename__ = "provider_networks"

    id = Column(Integer, primary_key=True, index=True)
    provider_id = Column(Integer, ForeignKey("providers.id"), nullable=False, index=True)
    scheme_id = Column(Integer, ForeignKey("schemes.id"), nullable=False, index=True)
    network_type = Column(String(60), nullable=False)
    # Network types: PRIME_HOSPITAL, COMPACT_HOSPITAL, GP_MEDIPHILA, GP_MEDIVALUE,
    # GP_MEDIPLUS, GP_MEDICURVE, PHARMACY_DIRECT, PHARMACY_CHRONIC_DSP,
    # DENTAL_DENIS, OPTICAL_ISOLESO, ONCOLOGY_ICON, HIV_DSP, DIALYSIS_DSP,
    # PROSTHESIS_MJ4L, PROSTHESIS_ICPS, APPLIANCE_PREFERRED, SMARTCARE
    effective_from = Column(Date, nullable=False)
    effective_to = Column(Date, nullable=True)  # NULL = currently active

    provider = relationship("Provider", back_populates="network_memberships")
    scheme = relationship("Scheme")

    __table_args__ = (
        UniqueConstraint("provider_id", "scheme_id", "network_type",
                         name="uq_provider_network"),
    )


