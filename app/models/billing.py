from sqlalchemy import (
    Column, Integer, String, Boolean, ForeignKey, DateTime, Date, Text, UniqueConstraint
)
from sqlalchemy.orm import relationship
from datetime import datetime, timezone
from app.database import Base


class ContributionRate(Base):
    """Monthly contribution rates per plan × member type.
    All monetary values are configurable per scheme — nothing hardcoded."""
    __tablename__ = "contribution_rates"

    id = Column(Integer, primary_key=True, index=True)
    plan_option_id = Column(Integer, ForeignKey("plan_options.id"), nullable=False, index=True)
    member_type = Column(String(30), nullable=False)  # PRINCIPAL | ADULT_DEPENDANT | CHILD
    monthly_rate_cents = Column(Integer, nullable=False)
    effective_year = Column(Integer, nullable=False)

    plan_option = relationship("PlanOption", back_populates="contribution_rates")

    __table_args__ = (
        UniqueConstraint("plan_option_id", "member_type", "effective_year",
                         name="uq_contribution_rate"),
    )


class MemberContribution(Base):
    """Contribution ledger — one row per member per billing month.
    Generated by the billing run; stores a snapshot of composition and amounts at billing time."""
    __tablename__ = "member_contributions"

    id = Column(Integer, primary_key=True, index=True)
    member_id = Column(Integer, ForeignKey("members.id"), nullable=False, index=True)
    scheme_id = Column(Integer, ForeignKey("schemes.id"), nullable=False, index=True)
    billing_month = Column(Date, nullable=False)  # always day=1

    # Snapshot of composition at billing time
    principal_cents = Column(Integer, nullable=False, default=0)
    adult_dependant_count = Column(Integer, nullable=False, default=0)
    adult_dependant_cents = Column(Integer, nullable=False, default=0)
    child_count = Column(Integer, nullable=False, default=0)
    child_cents = Column(Integer, nullable=False, default=0)
    child_cap_applied = Column(Boolean, nullable=False, default=False)

    # Late-joiner penalty
    late_joiner_penalty_pct = Column(Integer, nullable=False, default=0)
    late_joiner_surcharge_cents = Column(Integer, nullable=False, default=0)

    # Totals
    amount_due_cents = Column(Integer, nullable=False, default=0)
    amount_paid_cents = Column(Integer, nullable=False, default=0)

    # Payment info
    payment_date = Column(Date, nullable=True)
    payment_reference = Column(String(100), nullable=True)

    # Status: generated | paid | partially_paid | overdue | written_off
    status = Column(String(20), nullable=False, default="generated")

    generated_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))
    updated_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc),
                        onupdate=lambda: datetime.now(timezone.utc))
    modified_date = Column(DateTime(timezone=True), nullable=True)
    modified_user = Column(Integer, ForeignKey("users.id"), nullable=True)

    member = relationship("Member", backref="contributions")
    scheme = relationship("Scheme")

    __table_args__ = (
        UniqueConstraint("member_id", "billing_month", name="uq_member_contribution"),
    )


class BenefitBalance(Base):
    """Running per-member benefit balance per category per year.
    Created on enrolment and reset each 1 January via initialise_benefit_balances()."""
    __tablename__ = "benefit_balances"

    id = Column(Integer, primary_key=True, index=True)
    member_id = Column(Integer, ForeignKey("members.id"), nullable=False, index=True)
    scheme_id = Column(Integer, ForeignKey("schemes.id"), nullable=False, index=True)
    benefit_category = Column(String(100), nullable=False)
    benefit_year = Column(Integer, nullable=False)
    opening_balance_cents = Column(Integer, nullable=False, default=0)
    used_cents = Column(Integer, nullable=False, default=0)
    reserved_cents = Column(Integer, nullable=False, default=0)  # held by in-flight auths
    visits_used = Column(Integer, nullable=False, default=0)
    last_updated = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc),
                          onupdate=lambda: datetime.now(timezone.utc))

    member = relationship("Member", back_populates="benefit_balances")

    __table_args__ = (
        UniqueConstraint("member_id", "benefit_category", "benefit_year",
                         name="uq_benefit_balance"),
    )


