class Formulary(Base):
    """Formulary entries per plan × type. Drives formulary compliance in Stage 4 adjudication.
    reference_price_cents is used for generic reference pricing in Stage 7."""
    __tablename__ = "formulary"

    id = Column(Integer, primary_key=True, index=True)
    plan_option_id = Column(Integer, ForeignKey("plan_options.id"), nullable=False, index=True)
    formulary_type = Column(String(20), nullable=False)  # CHRONIC | ACUTE | ONCOLOGY | RADIOLOGY | PATHOLOGY
    nappi_code_id = Column(Integer, ForeignKey("nappi_codes.id"), nullable=True, index=True)
    tariff_code_id = Column(Integer, ForeignKey("tariff_codes.id"), nullable=True, index=True)
    cdl_condition = Column(String(100), nullable=True)  # e.g. HYPERTENSION — for chronic formulary
    is_covered = Column(Boolean, default=True)
    is_preferred = Column(Boolean, default=True)  # FALSE = generic substitution required
    reference_price_cents = Column(Integer, nullable=True)  # scheme reference price for generics
    max_quantity_per_script = Column(Integer, nullable=True)
    max_scripts_per_period = Column(Integer, nullable=True)
    period_days = Column(Integer, nullable=True)  # e.g. 30 for monthly
    copayment_if_non_formulary_pct = Column(Integer, nullable=True, default=20)
    effective_year = Column(Integer, nullable=False)

    plan_option = relationship("PlanOption", back_populates="formulary_entries")
    nappi = relationship("NappiCode", back_populates="formulary_entries")


class ChronicRegistration(Base):
    """CDL (Chronic Disease List) registration per member/dependant.
    Required for chronic benefit claims to pass Stage 3 PMB eligibility check."""
    __tablename__ = "chronic_registrations"

    id = Column(Integer, primary_key=True, index=True)
    scheme_id = Column(Integer, ForeignKey("schemes.id"), nullable=False, index=True)
    member_id = Column(Integer, ForeignKey("members.id"), nullable=False, index=True)
    dependant_id = Column(Integer, ForeignKey("dependants.id"), nullable=True)
    icd10_code_id = Column(Integer, ForeignKey("icd10_codes.id"), nullable=False)
    status = Column(String(20), nullable=False, default="PENDING")
    # PENDING | APPROVED | DECLINED | EXPIRED
    application_date = Column(Date, nullable=False)
    decision_date = Column(Date, nullable=True)
    decided_by = Column(Integer, ForeignKey("users.id"), nullable=True)
    expiry_date = Column(Date, nullable=True)  # annual renewal
    approved_medicines = Column(Text, nullable=True)  # JSON list of nappi_code_ids
    care_plan = Column(Text, nullable=True)  # JSON for DTP PMB approved services
    notes = Column(Text, nullable=True)
    is_pmb = Column(Boolean, default=True)
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))
    updated_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc),
                        onupdate=lambda: datetime.now(timezone.utc))
    modified_date = Column(DateTime(timezone=True), nullable=True)
    modified_user = Column(Integer, ForeignKey("users.id"), nullable=True)

    member = relationship("Member", back_populates="chronic_registrations")
    dependant = relationship("Dependant")
    icd10 = relationship("ICD10Code")
    decided_by_user = relationship("User", foreign_keys=[decided_by])


class ClaimAdjudicationLog(Base):
    """Immutable per-stage adjudication detail log.
    Written once by run_full_adjudication(); read by GET /claims/{id}/adjudication-log."""
    __tablename__ = "claim_adjudication_logs"

    id = Column(Integer, primary_key=True, index=True)
    claim_id = Column(Integer, ForeignKey("claims.id"), nullable=False, index=True)
    claim_line_id = Column(Integer, ForeignKey("claim_lines.id"), nullable=True, index=True)
    stage = Column(Integer, nullable=False)        # 1-7
    stage_name = Column(String(50), nullable=False)  # ADMIN | INDUSTRY | PMB | CLINICAL | SCHEME | PMB_OVERRIDE | RATE_CALC
    rule_code = Column(String(20), nullable=False)   # e.g. ADM001, SCH003
    result = Column(String(20), nullable=False)      # PASS | FAIL | FLAG | INFO | OVERRIDE
    detail = Column(Text, nullable=True)             # JSON with rule-specific context
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))

    claim = relationship("Claim", back_populates="adjudication_logs")


class Dispute(Base):
    """Dispute register per Medical Schemes Act timeline rules.
    Member has 90 days from rejection to lodge; administrator has 30 days to respond."""
    __tablename__ = "disputes"

    id = Column(Integer, primary_key=True, index=True)
    scheme_id = Column(Integer, ForeignKey("schemes.id"), nullable=False, index=True)
    dispute_number = Column(String(50), unique=True, nullable=False, index=True)
    member_id = Column(Integer, ForeignKey("members.id"), nullable=False, index=True)
    claim_id = Column(Integer, ForeignKey("claims.id"), nullable=True)
    dispute_type = Column(String(50), nullable=False)
    # CLAIM_REJECTION | BENEFIT_LIMIT | AUTHORISATION | CONTRIBUTION | OTHER
    description = Column(Text, nullable=False)
    status = Column(String(20), nullable=False, default="OPEN")
    # OPEN | UNDER_REVIEW | UPHELD | DISMISSED | ESCALATED_TO_CMS
    date_received = Column(Date, nullable=False)
    member_deadline = Column(Date, nullable=False)   # date_received + 90 days (MSA)
    admin_deadline = Column(Date, nullable=False)    # date_received + 30 days (MSA)
    resolution = Column(Text, nullable=True)
    escalated_to_cms = Column(Boolean, default=False)
    cms_reference = Column(String(100), nullable=True)
    resolved_by = Column(Integer, ForeignKey("users.id"), nullable=True)
    resolved_at = Column(DateTime(timezone=True), nullable=True)
    created_by = Column(Integer, ForeignKey("users.id"), nullable=True)
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))
    updated_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc),
                        onupdate=lambda: datetime.now(timezone.utc))
    modified_date = Column(DateTime(timezone=True), nullable=True)
    modified_user = Column(Integer, ForeignKey("users.id"), nullable=True)

    member = relationship("Member", back_populates="disputes")
    claim = relationship("Claim")
    resolved_by_user = relationship("User", foreign_keys=[resolved_by])
    created_by_user = relationship("User", foreign_keys=[created_by])
